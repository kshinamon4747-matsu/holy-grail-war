/**
 * 二騎のサーヴァント間の縁のセリフを取得
 * @returns AffinityPair | undefined
 */
export function getAffinityDialogue(idA: number, idB: number): AffinityPair | undefined {
  return PAIR_MAP.get(pairKey(idA, idB));
}

