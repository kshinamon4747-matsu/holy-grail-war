/**
 * サーヴァント縁セリフシステム
 *
 * 特別な関係のあるサーヴァントの組が遭遇・戦闘した際に、専用のセリフを出力する。
 * - サーヴァントIDの組でマッチング (順不同)
 * - encounter: 遭遇時の各サーヴァントのセリフ
 * - clash: 戦闘中の各サーヴァントのセリフ
 * - specialLog: 特殊な状況の描写
 */

// ─── 型 ───

export interface AffinityPair {
  /** サーヴァントIDの組 */
  ids: [number, number];
  /** 遭遇時のセリフ — servantId → セリフ配列 (ランダム選択) */
  encounter: Record<number, string[]>;
  /** 戦闘中のセリフ (任意) */
  clash?: Record<number, string[]>;
  /** 特殊な状況の描写 */
  specialLog?: string;
}

// ─── ユーティリティ ───

function pairKey(a: number, b: number): string {
  return a < b ? `${a}_${b}` : `${b}_${a}`;
}

